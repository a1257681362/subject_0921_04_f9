    remark         VARCHAR(500),
    operator       VARCHAR(32)    NOT NULL,
    biz_time       TIMESTAMP      NOT NULL,
    request_no     VARCHAR(64)    NOT NULL,
    version        INT            NOT NULL DEFAULT 0,
    create_by      BIGINT,
    create_time    TIMESTAMP      NOT NULL DEFAULT CURRENT_TIMESTAMP,
    update_by      BIGINT,
    update_time    TIMESTAMP      NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_handover_type CHECK (type IN ('PICKUP', 'RETURN')),
    CONSTRAINT ck_handover_fuel CHECK (fuel_reading BETWEEN 0 AND 100)
);

CREATE INDEX IF NOT EXISTS idx_handover_order ON t_rental_handover (order_id);

-- 订单事件流水：下单/交车/还车结算/归档/冲销 全部留痕；
-- 通用流转动作名取状态机配置（可扩展），故 event_type 不设 CHECK 枚举。
CREATE TABLE IF NOT EXISTS t_rental_order_event (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id       BIGINT         NOT NULL,
    event_type     VARCHAR(32)    NOT NULL,           -- CREATE/PICKUP/RETURN/ARCHIVE/REVERSE/RENAME 及配置新增动作
    detail         VARCHAR(500),
    operator       VARCHAR(32)    NOT NULL,
    biz_time       TIMESTAMP      NOT NULL,
    request_no     VARCHAR(64)    NOT NULL,
    version        INT            NOT NULL DEFAULT 0,
    create_by      BIGINT,
    create_time    TIMESTAMP      NOT NULL DEFAULT CURRENT_TIMESTAMP,
    update_by      BIGINT,
    update_time    TIMESTAMP      NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_order_event_order ON t_rental_order_event (order_id);

-- rental-fsm-1：既有文件库平滑迁移（新建库由上面的 CREATE TABLE 直接带出）
-- 1) 状态/事件列扩容以容纳配置新增的状态与动作；2) 去掉状态枚举 CHECK，交给状态机配置。
ALTER TABLE t_rental_order ALTER COLUMN status SET DATA TYPE VARCHAR(32);
ALTER TABLE t_rental_order_event ALTER COLUMN event_type SET DATA TYPE VARCHAR(32);
ALTER TABLE t_rental_order DROP CONSTRAINT IF EXISTS ck_rental_order_status;

-- 状态流转历史（交车生命周期审计链）：每次成功流转在业务事务内落一行。
-- 动作/状态为字符串、不设 CHECK：新增状态只改状态机配置，不改表结构。
-- 与事件流水分工：event 记业务动作叙述，transition 结构化记录每次状态变化，
-- 可按动作、起止状态、版本、关联交接、操作人/业务时间/请求号逐条追溯。
CREATE TABLE IF NOT EXISTS t_rental_order_transition (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id       BIGINT         NOT NULL,
    action         VARCHAR(32)    NOT NULL,           -- 流转动作（状态机配置 action）
    from_status    VARCHAR(32)    NOT NULL,           -- 起始状态
    to_status      VARCHAR(32)    NOT NULL,           -- 目标状态
    from_version   INT            NOT NULL,           -- 流转前订单版本（乐观锁）
    to_version     INT            NOT NULL,           -- 流转后订单版本
    handover_id    BIGINT,                            -- 关联交接记录（交车/还车；纯状态动作为空）
    remark         VARCHAR(500),                      -- 现场备注/原因（如冲销原因）
    operator       VARCHAR(32)    NOT NULL,
    biz_time       TIMESTAMP      NOT NULL,
    request_no     VARCHAR(64)    NOT NULL,
    version        INT            NOT NULL DEFAULT 0,
    create_by      BIGINT,
    create_time    TIMESTAMP      NOT NULL DEFAULT CURRENT_TIMESTAMP,
    update_by      BIGINT,
    update_time    TIMESTAMP      NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_order_transition_order ON t_rental_order_transition (order_id, id);

-- 租车单客户姓名拼音索引（rental-name-search-1）
-- 派生索引数据：与订单一一对应（order_id 即主键），下单/改名在同一业务事务内同步，
-- 另提供全量重建与启动自愈。索引行不随行业务四要素，业务动作留痕见 t_rental_order_event。
-- 统一存无分隔符小写串：full_pinyin 逐字全拼（多音字取常用首读，非汉字原样保留），
-- initials 逐字拼音首字母；customer_name 冗余原文，支持中文/外文字母直查。
CREATE TABLE IF NOT EXISTS t_rental_order_name_index (
    order_id         BIGINT       NOT NULL,
    customer_name    VARCHAR(64)  NOT NULL,
    normalized_name  VARCHAR(64),             -- NFKC+小写+去标点后的姓名，支持中文/外文字母直查
    full_pinyin      VARCHAR(512),
    initials         VARCHAR(64),
    create_time      TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    update_time      TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_rental_order_name_index PRIMARY KEY (order_id)
);

-- 入口幂等请求记录（request_no 库层唯一，重复提交在此拦截）
CREATE TABLE IF NOT EXISTS t_idempotent_request (
    request_no     VARCHAR(64)    PRIMARY KEY,
    status         VARCHAR(16)    NOT NULL,           -- PROCESSING / DONE / FAILED
    operator       VARCHAR(32),
    response_body  CLOB,
    create_time    TIMESTAMP      NOT NULL DEFAULT CURRENT_TIMESTAMP,
    update_time    TIMESTAMP      NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_idempotent_status CHECK (status IN ('PROCESSING', 'DONE', 'FAILED'))
);

-- ===========================================================================
-- 网点树（branch-1）：闭包表管理区域层级
-- 背景：网点调度反馈旧处理方式忙时漏单、区域层级调整频繁。
-- 设计：t_branch 存节点；t_branch_closure 存祖先-子孙全量链路（含 depth=0 自闭环），
--       任意层级查询均为单索引等值扫描，性能与树深无关；
--       子树迁移单事务原子完成：删子树外部旧链路（内部链路保留）-> 接新祖先链 ->
--       改 parent_id（乐观锁）-> 写事件，中途失败整体回滚，不留半截链路；
--       变更全程留痕 t_branch_event；灰度规则落库 t_gray_rule，运行时开关。
-- ===========================================================================

-- 网点节点（全量留痕，禁止物理删除；parent_id = 0 表示根，允许森林）
CREATE TABLE IF NOT EXISTS t_branch (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    branch_code  VARCHAR(32)  NOT NULL,
    name         VARCHAR(64)  NOT NULL,
    parent_id    BIGINT       NOT NULL DEFAULT 0,   -- 0 = 根节点
    sort_order   INT          NOT NULL DEFAULT 0,   -- 同级排序配置，小的在前，同值按 id
    operator     VARCHAR(32)  NOT NULL,
    biz_time     TIMESTAMP    NOT NULL,
    request_no   VARCHAR(64)  NOT NULL,
    version      INT          NOT NULL DEFAULT 0,
    create_by    BIGINT,
    create_time  TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    update_by    BIGINT,
    update_time  TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_branch_code UNIQUE (branch_code)
);

-- 闭包表：祖先-子孙全量链路。派生索引数据，由建点/迁移整体重写，
-- 不随行业务四要素；操作留痕见 t_branch_event。
CREATE TABLE IF NOT EXISTS t_branch_closure (
    ancestor_id   BIGINT NOT NULL,
    descendant_id BIGINT NOT NULL,
    depth         INT    NOT NULL,              -- 0=自身，1=父子直连，以此类推
    CONSTRAINT pk_branch_closure PRIMARY KEY (ancestor_id, descendant_id)
);

-- 查祖先/到根路径：按子孙反查
CREATE INDEX IF NOT EXISTS idx_closure_descendant ON t_branch_closure (descendant_id, ancestor_id);

-- 树变更留痕：建点 / 子树迁移 / 同级排序（试点观察期审计依据）
CREATE TABLE IF NOT EXISTS t_branch_event (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    branch_id    BIGINT       NOT NULL,
    event_type   VARCHAR(16)  NOT NULL,           -- CREATE / MOVE / SORT
    detail       VARCHAR(500),
    operator     VARCHAR(32)  NOT NULL,
    biz_time     TIMESTAMP    NOT NULL,
    request_no   VARCHAR(64)  NOT NULL,
    version      INT          NOT NULL DEFAULT 0,
    create_by    BIGINT,
    create_time  TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    update_by    BIGINT,
    update_time  TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_branch_event_type CHECK (event_type IN ('CREATE', 'MOVE', 'SORT'))
);

CREATE INDEX IF NOT EXISTS idx_branch_event_branch ON t_branch_event (branch_id);

-- 灰度规则：scene + branch_code 唯一；branch_code = '*' 表示全量放开。
-- 试点期只放单个网点（其整棵子树经闭包表判定放行），观察期满置 '*' ON 推全。
CREATE TABLE IF NOT EXISTS t_gray_rule (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    scene        VARCHAR(32)  NOT NULL,           -- 本期固定 BRANCH_TREE
    branch_code  VARCHAR(32)  NOT NULL,           -- 网点编码；'*' = 全量
    status       VARCHAR(8)   NOT NULL DEFAULT 'ON',  -- ON 生效 / OFF 停用
    operator     VARCHAR(32)  NOT NULL,
    biz_time     TIMESTAMP    NOT NULL,
    request_no   VARCHAR(64)  NOT NULL,
    version      INT          NOT NULL DEFAULT 0,
    create_by    BIGINT,
    create_time  TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    update_by    BIGINT,
    update_time  TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_gray_rule UNIQUE (scene, branch_code),
    CONSTRAINT ck_gray_rule_status CHECK (status IN ('ON', 'OFF'))
);

