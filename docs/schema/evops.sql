-- ===========================================================================
-- 登录态多端会话（auth-1）：账号角色 / JWT 访问令牌 / 刷新令牌一次性轮换
-- 背景：旺季前把人工盯登录改为系统管理。JWT 携带调度员身份与角色；访问令牌
--       短期有效、过期走 /api/auth/refresh 换新（前端拦截到 401 无感刷新重试）；
--       刷新令牌一次性轮换（复用已轮换的旧令牌视为被盗，整链会话吊销）；
--       修改密码后 token_version 自增并吊销该账号全部端会话，全部端强制下线；
--       登出立即吊销会话，该会话已签发的访问令牌即刻失效（访问令牌按 sid 绑定会话）。
-- 约定：- 访问令牌 JWT(HS256) claims: sub/username、uid、roles、tv(tokenVersion)、
--         sid(会话)、jti、type=ACCESS、iat/exp；
--       - 刷新令牌为不透明随机串（32 字节），库存 SHA-256 哈希，只存哈希不存原文；
--       - 每次登录产生独立会话行（web/app 可并存=多端）；轮换复用同一会话行，
--         旧刷新令牌哈希留在 prev_refresh_token_hash 用于重放侦测；
--       - 密码用 PBKDF2WithHmacSHA256（随机盐 + 迭代）存储，永不存明文。
-- ===========================================================================

-- 系统账号（调度员/主管/管理员）
