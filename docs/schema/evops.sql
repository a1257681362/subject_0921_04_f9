-- ===========================================================================
-- 对账（recon-1）：双方流水自动勾稽 / 差异清单与手工核销 / 日结对账单 /
--                 配置变更夜间批处理 / 周期作业运行记录
-- 背景：网点新换负责人，先把资金账理清楚。白天系统繁忙不改配置，配置变更落
--       PENDING 变更单，夜间批处理统一生效；凌晨自动拉双方流水勾稽并在日结后
--       出对账单，次日早晨依据作业运行记录核对结果。
-- 约定：- 内部流水从租车单结算/冲销事件抽取，外部流水由渠道对账文件导入；
--       - 勾稽按业务参考号配对，金额差在容差内且状态一致视为匹配；
--       - 金额超差/状态不一致/单边账进差异清单，手工核销必须填原因，核销即时清零；
--       - 同网点同业务日可重跑：已消失差异自动消解（AUTO），人工核销结果不翻案。
-- ===========================================================================

-- 内部流水（本方账面）：按 网点+业务日 从租车单事件抽取，ref_no 即订单号
CREATE TABLE IF NOT EXISTS t_recon_txn_internal (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    branch_code    VARCHAR(32)  NOT NULL,
    biz_date       DATE         NOT NULL,
    ref_no         VARCHAR(40)  NOT NULL,           -- 业务参考号（订单号）
    txn_type       VARCHAR(16)  NOT NULL,           -- SETTLE 结算 / REVERSE 冲销
    amount         DECIMAL(12,2) NOT NULL,
    status         VARCHAR(16)  NOT NULL,           -- SETTLED / REVERSED
    order_id       BIGINT,
    operator       VARCHAR(32)  NOT NULL,
    biz_time       TIMESTAMP    NOT NULL,
    request_no     VARCHAR(64)  NOT NULL,
    version        INT          NOT NULL DEFAULT 0,
    create_by      BIGINT,
    create_time    TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    update_by      BIGINT,
    update_time    TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    -- 同一业务参考号只抽一笔：重复拉取幂等，库层兜底
    CONSTRAINT uk_recon_internal_ref UNIQUE (ref_no, txn_type),
    CONSTRAINT ck_recon_internal_type CHECK (txn_type IN ('SETTLE', 'REVERSE')),
    CONSTRAINT ck_recon_internal_status CHECK (status IN ('SETTLED', 'REVERSED'))
);

CREATE INDEX IF NOT EXISTS idx_recon_internal_day ON t_recon_txn_internal (branch_code, biz_date);

-- 外部流水（渠道方账面）：渠道对账文件导入，同外部流水号重复导入按最新内容覆盖
CREATE TABLE IF NOT EXISTS t_recon_txn_external (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    branch_code    VARCHAR(32)  NOT NULL,
    biz_date       DATE         NOT NULL,
    ref_no         VARCHAR(40),                     -- 渠道单自身流水号
    external_ref_no VARCHAR(40) NOT NULL,           -- 渠道侧关联的业务参考号（对齐内部订单号）
    txn_type       VARCHAR(16)  NOT NULL,           -- SETTLE / REFUND 等，渠道原文
    amount         DECIMAL(12,2) NOT NULL,
    status         VARCHAR(16)  NOT NULL,           -- 渠道状态原文（SUCCESS/...）
    raw_text       VARCHAR(500),
    operator       VARCHAR(32)  NOT NULL,
    biz_time       TIMESTAMP    NOT NULL,
    request_no     VARCHAR(64)  NOT NULL,
    version        INT          NOT NULL DEFAULT 0,
    create_by      BIGINT,
    create_time    TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    update_by      BIGINT,
    update_time    TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    -- 同一业务参考号同一类型重复导入按最新内容覆盖（次日退款 REFUND 是另一行）
    CONSTRAINT uk_recon_external_ref UNIQUE (external_ref_no, txn_type)
);

CREATE INDEX IF NOT EXISTS idx_recon_external_day ON t_recon_txn_external (branch_code, biz_date);

-- 对账批次：一网点一业务日一次勾稽一行，可重跑（RUNNING -> DONE/FAILED）
CREATE TABLE IF NOT EXISTS t_recon_batch (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    batch_no       VARCHAR(40)  NOT NULL,
    branch_code    VARCHAR(32)  NOT NULL,
    biz_date       DATE         NOT NULL,
    status         VARCHAR(8)   NOT NULL,           -- RUNNING / DONE / FAILED
    trigger_type   VARCHAR(16)  NOT NULL,           -- SCHEDULED 周期 / MANUAL 手工 / DAILY 日结
    internal_count INT          NOT NULL DEFAULT 0,
    external_count INT          NOT NULL DEFAULT 0,
    matched_count  INT          NOT NULL DEFAULT 0,
    diff_count     INT          NOT NULL DEFAULT 0, -- 本次勾稽产出的未核销差异数
    tolerance_amount DECIMAL(12,2) NOT NULL DEFAULT 0,
    started_at     TIMESTAMP    NOT NULL,
    finished_at    TIMESTAMP,
    remark         VARCHAR(500),
    operator       VARCHAR(32)  NOT NULL,
    biz_time       TIMESTAMP    NOT NULL,
    request_no     VARCHAR(64)  NOT NULL,
    version        INT          NOT NULL DEFAULT 0,
    create_by      BIGINT,
    create_time    TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    update_by      BIGINT,
    update_time    TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_recon_batch_no UNIQUE (batch_no),
    CONSTRAINT ck_recon_batch_status CHECK (status IN ('RUNNING', 'DONE', 'FAILED')),
    CONSTRAINT ck_recon_batch_trigger CHECK (trigger_type IN ('SCHEDULED', 'MANUAL', 'DAILY'))
);

CREATE INDEX IF NOT EXISTS idx_recon_batch_day ON t_recon_batch (branch_code, biz_date);

-- 差异清单：金额超差 / 状态不一致 / 单边账。diff_key 幂等标识支撑同批次重跑。
CREATE TABLE IF NOT EXISTS t_recon_diff (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    branch_code    VARCHAR(32)  NOT NULL,
    biz_date       DATE         NOT NULL,
    batch_id       BIGINT       NOT NULL,
    diff_type      VARCHAR(24)  NOT NULL,
    -- AMOUNT_MISMATCH 金额超差 / STATUS_MISMATCH 状态不一致 /
    -- AMOUNT_STATUS_MISMATCH 二者皆不符 / INTERNAL_ONLY 单边(本方) / EXTERNAL_ONLY 单边(渠道)
    diff_key       VARCHAR(80)  NOT NULL,           -- 幂等键：I:<内部id> / E:<外部id> / IE:<内部id>-<外部id>
    internal_txn_id BIGINT,
    external_txn_id BIGINT,
    ref_no         VARCHAR(40),
    internal_amount DECIMAL(12,2),
    external_amount DECIMAL(12,2),
    amount_gap     DECIMAL(12,2),                   -- 内部-外部差额（单边账取在账方金额）
    internal_status VARCHAR(16),
    external_status VARCHAR(16),
    status         VARCHAR(8)   NOT NULL DEFAULT 'OPEN',   -- OPEN 待核销 / RESOLVED 已清零
    resolve_type   VARCHAR(8),                      -- MANUAL 人工核销 / AUTO 重跑自动消解
    resolve_reason VARCHAR(500),                    -- 人工核销必填原因
    resolve_operator VARCHAR(32),
    resolve_time   TIMESTAMP,
    operator       VARCHAR(32)  NOT NULL,
    biz_time       TIMESTAMP    NOT NULL,
    request_no     VARCHAR(64)  NOT NULL,
    version        INT          NOT NULL DEFAULT 0,
    create_by      BIGINT,
    create_time    TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    update_by      BIGINT,
    update_time    TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_recon_diff UNIQUE (branch_code, biz_date, diff_key),
    CONSTRAINT ck_recon_diff_type CHECK (diff_type IN (
        'AMOUNT_MISMATCH', 'STATUS_MISMATCH', 'AMOUNT_STATUS_MISMATCH',
        'INTERNAL_ONLY', 'EXTERNAL_ONLY')),
    CONSTRAINT ck_recon_diff_status CHECK (status IN ('OPEN', 'RESOLVED')),
    CONSTRAINT ck_recon_resolve_type CHECK (resolve_type IS NULL OR resolve_type IN ('MANUAL', 'AUTO'))
);

CREATE INDEX IF NOT EXISTS idx_recon_diff_status ON t_recon_diff (branch_code, biz_date, status);

-- 对账单：日结后一网点一业务日一份；未确认前可随重跑刷新，CONFIRMED 后冻结
CREATE TABLE IF NOT EXISTS t_recon_statement (
