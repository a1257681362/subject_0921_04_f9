    password_hash  VARCHAR(200)  NOT NULL,           -- PBKDF2: v1$iterations$saltHex$hashHex
    roles          VARCHAR(200)  NOT NULL,           -- 角色逗号分隔：DISPATCHER/MANAGER/ADMIN
    status         VARCHAR(8)    NOT NULL DEFAULT 'ACTIVE', -- ACTIVE 启用 / DISABLED 停用
    token_version  INT           NOT NULL DEFAULT 0, -- 改密自增；访问令牌 tv 不一致即失效（全端下线）
