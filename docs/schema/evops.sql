    operator             VARCHAR(32)   NOT NULL,
    biz_time             TIMESTAMP     NOT NULL,
    request_no           VARCHAR(64)   NOT NULL,
    version              INT           NOT NULL DEFAULT 0,
    create_by            BIGINT,
    create_time          TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    update_by            BIGINT,
    update_time          TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_turnover_correction_day ON t_turnover_correction (branch_code, biz_date);

-- 周转率作业运行记录：凌晨关账 / 手工重算逐次留痕，审计据此核对
CREATE TABLE IF NOT EXISTS t_turnover_job_run (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    job_type       VARCHAR(16)  NOT NULL,            -- DAILY_CLOSE 凌晨关账 / MANUAL_RUN 手工重算
    fired_at       TIMESTAMP    NOT NULL,
    finished_at    TIMESTAMP,
    status         VARCHAR(8),                       -- NULL 进行中 / SUCCESS / FAILED
    biz_date       DATE         NOT NULL,
    branch_count   INT          NOT NULL DEFAULT 0,  -- 本次覆盖网点数
    success_count  INT          NOT NULL DEFAULT 0,  -- 生成/刷新成功网点数
    skip_count     INT          NOT NULL DEFAULT 0,  -- 已关账跳过网点数
    summary        VARCHAR(1000),
    error_detail   CLOB,
    create_time    TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    update_time    TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_turnover_job_type CHECK (job_type IN ('DAILY_CLOSE', 'MANUAL_RUN')),
    CONSTRAINT ck_turnover_job_status CHECK (status IN ('SUCCESS', 'FAILED'))
);

CREATE INDEX IF NOT EXISTS idx_turnover_job_run_fired ON t_turnover_job_run (biz_date, id);

