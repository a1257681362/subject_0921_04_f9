-- ===========================================================================
-- 车辆档期（schedule-1）：预约占位 / 缓冲隔离 / 锁位超时自动释放 / 冲突推荐空档
-- 背景：前任未交接，车辆档期此前无人系统管理，现场靠口头/记忆，撞单与超时占位频发。
--       本期把车辆档期统一收归系统：预约冲突按“区间重叠（含前后缓冲）”判定；
--       占位需在锁位时限内确认，取消或超时未确认自动释放占位；冲突时推荐最近空档。
--       本期不含审批流（预约->审批/下单另起下期），档期只负责时间占用本身。
-- 口径：- 占用按半开区间 [start_time, end_time) 比较，结束时刻=下一单开始时刻不冲突；
--       - 每段占用前后各留 buffer（默认 12 分钟，evops.schedule.buffer-minutes），
--         新区间落入 [a-buffer, b+buffer) 即冲突；与相邻占用间隔恰为 buffer 不冲突，
--         小于 buffer（如 11 分钟）拒绝；
--       - 占位 HELD 设 held_deadline=占位时刻+锁位时限（默认 25 分钟，
--         evops.schedule.lock-ttl-minutes），到期未确认由周期作业自动置 EXPIRED 释放；
--       - CANCELLED / EXPIRED 行保留留痕但不再占用档期，冲突判定与空档推荐均忽略。
-- ===========================================================================

CREATE TABLE IF NOT EXISTS t_vehicle_schedule (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    vehicle_id     BIGINT       NOT NULL,              -- 占用车辆
    start_time     TIMESTAMP    NOT NULL,              -- 占用开始（半开区间，含）
    end_time       TIMESTAMP    NOT NULL,              -- 占用结束（半开区间，不含）
    status         VARCHAR(10)  NOT NULL DEFAULT 'HELD', -- HELD 占位 / CONFIRMED 已确认 / CANCELLED 已取消 / EXPIRED 超时释放
    customer_name  VARCHAR(64),                        -- 预约客户（可空）
    order_id       BIGINT,                             -- 关联租车单（本期预约可暂不挂单，审批/下单下期接通）
    held_deadline  TIMESTAMP,                          -- HELD 锁位截止（占位时刻 + lock-ttl-minutes）
    confirmed_time TIMESTAMP,                          -- 确认时间
    cancel_reason  VARCHAR(500),                       -- 取消原因
    released_time  TIMESTAMP,                          -- 取消/超时释放时间
    operator       VARCHAR(32)  NOT NULL,
    biz_time       TIMESTAMP    NOT NULL,
    request_no     VARCHAR(64)  NOT NULL,
    version        INT          NOT NULL DEFAULT 0,
    create_by      BIGINT,
    create_time    TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    update_by      BIGINT,
    update_time    TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_schedule_status CHECK (status IN ('HELD', 'CONFIRMED', 'CANCELLED', 'EXPIRED'))
);

-- 档期冲突/空档查询主路径：按车辆取占用区间；扫描超时占位按 status+deadline。
CREATE INDEX IF NOT EXISTS idx_vehicle_schedule_window
    ON t_vehicle_schedule (vehicle_id, start_time, end_time);
CREATE INDEX IF NOT EXISTS idx_vehicle_schedule_hold
    ON t_vehicle_schedule (status, held_deadline);

MERGE INTO t_evops_schema_version (version_no, description)
KEY (version_no)
VALUES ('schedule-1', '车辆档期：预约区间重叠判定（前后缓冲12分钟）、占位锁位25分钟超时自动释放、取消释放、冲突推荐最近空档；审批流下期');
